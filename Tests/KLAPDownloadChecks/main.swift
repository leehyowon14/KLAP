precondition(state.transcribing && state.displayCurrent==1 && state.displayTotal==2 && state.displayFraction==0.25)
state.apply(LectureTranscriptProgressData(ID:"a",Stage:"transcribed",Path:"/tmp/a.txt",Error:""))
state.apply(LectureTranscriptProgressData(ID:"b",Stage:"transcribe",Path:"",Error:"",Progress:0.2))
precondition(state.displayCurrent==2 && state.displayFraction==0.6)
state.apply(LectureTranscriptProgressData(ID:"b",Stage:"transcript-error",Path:"",Error:"failed"))
precondition(state.displayFraction==1)
