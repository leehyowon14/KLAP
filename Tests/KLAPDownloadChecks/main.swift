state.apply(.init(ID:"unknown",Stage:"done",Bytes:1,TotalBytes:1,Error:""))
precondition(state.rows.count==3)
state.apply(.init(ID:"a",Stage:"download",Bytes:200,TotalBytes:100,Error:""))
precondition(state.rows["a"]?.fraction==1)
state.apply(.init(ID:"b",Stage:"download",Bytes:-1,TotalBytes:0,Error:""))
precondition(state.rows["b"]?.bytes==0 && state.rows["b"]?.fraction==nil)
state.apply([.init(ID:"a",Path:"/tmp/a.mp4",Bytes:100,Skipped:false,Error:""),.init(ID:"b",Path:"",Bytes:0,Skipped:false,Error:"지원하지 않음")])
state.finish(error:nil,receivedResult:true)
precondition(state.completed==1 && state.retryIDs == ["b","c"] && !state.running)
state.begin(["a"])
